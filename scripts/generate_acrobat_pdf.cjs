const fs = require('fs');
const path = require('path');

function createSimplePDF(title, subtitle, sections, outputPath) {
  // Build a standard text-based PDF 1.4 stream
  const contentLines = [];
  contentLines.push("BT");
  contentLines.push("/F1 22 Tf");
  contentLines.push("50 780 Td");
  contentLines.push(`(${escapePDF(title)}) Tj`);
  contentLines.push("ET");

  contentLines.push("BT");
  contentLines.push("/F1 12 Tf");
  contentLines.push("50 755 Td");
  contentLines.push(`(${escapePDF(subtitle)}) Tj`);
  contentLines.push("ET");

  let y = 720;
  for (const section of sections) {
    if (y < 80) break;
    contentLines.push("BT");
    contentLines.push("/F2 14 Tf");
    contentLines.push(`50 ${y} Td`);
    contentLines.push(`(${escapePDF(section.heading)}) Tj`);
    contentLines.push("ET");
    y -= 22;

    for (const line of section.lines) {
      if (y < 60) break;
      contentLines.push("BT");
      contentLines.push("/F1 10 Tf");
      contentLines.push(`60 ${y} Td`);
      contentLines.push(`(${escapePDF(line)}) Tj`);
      contentLines.push("ET");
      y -= 16;
    }
    y -= 14;
  }

  // Footer
  contentLines.push("BT");
  contentLines.push("/F1 8 Tf");
  contentLines.push("50 30 Td");
  contentLines.push(`(Generated by AKUL DRAVIN DIGITAL SERVICES • Verified for Adobe Acrobat DC • ${new Date().toLocaleDateString('en-GB')}) Tj`);
  contentLines.push("ET");

  const streamContent = contentLines.join("\n");
  const streamLength = Buffer.byteLength(streamContent, 'utf-8');

  let pdf = "";
  const offsets = [];

  function addObj(str) {
    offsets.push(Buffer.byteLength(pdf, 'utf-8'));
    pdf += str + "\n";
  }

  pdf += "%PDF-1.4\n";

  // Obj 1: Catalog
  addObj("1 0 obj\n<< /Type /Catalog /Pages 2 0 R >>\nendobj");

  // Obj 2: Pages
  addObj("2 0 obj\n<< /Type /Pages /Kids [3 0 R] /Count 1 >>\nendobj");

  // Obj 3: Page
  addObj("3 0 obj\n<< /Type /Page /Parent 2 0 R /MediaBox [0 0 595 842] /Contents 4 0 R /Resources << /Font << /F1 5 0 R /F2 6 0 R >> >> >>\nendobj");

  // Obj 4: Content Stream
  addObj(`4 0 obj\n<< /Length ${streamLength} >>\nstream\n${streamContent}\nendstream\nendobj`);

  // Obj 5: Font Helvetica
  addObj("5 0 obj\n<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica >>\nendobj");

  // Obj 6: Font Helvetica-Bold
  addObj("6 0 obj\n<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica-Bold >>\nendobj");

  const xrefStart = Buffer.byteLength(pdf, 'utf-8');
  pdf += "xref\n";
  pdf += `0 ${offsets.length + 1}\n`;
  pdf += "0000000000 65535 f \n";
  for (const off of offsets) {
    pdf += String(off).padStart(10, '0') + " 00000 n \n";
  }

  pdf += "trailer\n";
  pdf += `<< /Size ${offsets.length + 1} /Root 1 0 R >>\n`;
  pdf += "startxref\n";
  pdf += `${xrefStart}\n`;
  pdf += "%%EOF\n";

  fs.writeFileSync(outputPath, pdf, 'utf-8');
  console.log(`✓ Generated PDF: ${outputPath}`);
}

function escapePDF(str) {
  return str.replace(/\\/g, '\\\\').replace(/\(/g, '\\(').replace(/\)/g, '\\)');
}

